#!/usr/bin/env python3
"""Tiny HTML-syntax-to-freestanding-C experiment; not a bootable kernel."""
from __future__ import annotations

import argparse
from html.parser import HTMLParser
from pathlib import Path


class CompileError(ValueError):
    pass


class KernelParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.stack: list[str] = []
        self.instructions: list[tuple[str, str]] = []
        self.current_print: list[str] = []
        self.root_seen = False
        self.boot_seen = False
        self.halted = False

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        parent = self.stack[-1] if self.stack else None
        pairs = dict(attrs)
        if len(pairs) != len(attrs):
            raise CompileError(f"duplicate attributes on <{tag}>")
        if tag == "kernel" and parent is None and not self.root_seen:
            if set(pairs) - {"arch"} or pairs.get("arch", "x86_64") != "x86_64":
                raise CompileError("only <kernel arch=\"x86_64\"> is supported")
            self.root_seen = True
        elif tag == "onboot" and parent == "kernel" and not self.boot_seen and not attrs:
            self.boot_seen = True
        elif tag == "print" and parent == "onboot" and not attrs and not self.halted:
            self.current_print = []
        elif tag == "halt" and parent == "onboot" and not attrs and not self.halted:
            self.halted = True
            self.instructions.append(("halt", ""))
        else:
            raise CompileError(f"<{tag}> is not allowed under <{parent}>")
        self.stack.append(tag)

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self.handle_starttag(tag, attrs)
        self.handle_endtag(tag)

    def handle_endtag(self, tag: str) -> None:
        if not self.stack or self.stack[-1] != tag:
            raise CompileError(f"unexpected closing tag </{tag}>")
        if tag == "print":
            message = "".join(self.current_print)
            if not message or len(message.encode("utf-8")) > 4096:
                raise CompileError("<print> must contain 1..4096 UTF-8 bytes")
            self.instructions.append(("print", message))
        self.stack.pop()

    def handle_data(self, data: str) -> None:
        if self.stack and self.stack[-1] == "print":
            self.current_print.append(data)
        elif data.strip():
            raise CompileError("text is only allowed inside <print>")

    def finish(self) -> list[tuple[str, str]]:
        if self.stack or not (self.root_seen and self.boot_seen):
            raise CompileError("expected closed <kernel><onboot>...</onboot></kernel>")
        if not any(op == "print" for op, _ in self.instructions):
            raise CompileError("at least one <print> is required")
        return self.instructions


def compile_html(source: str) -> str:
    p = KernelParser()
    try:
        p.feed(source)
        p.close()
        instructions = p.finish()
    except (ValueError, AssertionError) as e:
        raise CompileError(str(e)) from e
    lines = [
        "/* Generated by htmlk prototype: QEMU debugcon (port 0xE9), NOT a boot image. */",
        "#if !defined(__x86_64__)",
        '#error "x86_64 only"',
        "#endif",
        "static inline void io_outb(unsigned short port, unsigned char v) {",
        '  __asm__ volatile ("outb %0, %1" : : "a"(v), "Nd"(port));',
        "}",
        "static inline void serial_init(void) {",
        "  io_outb(0x3f9, 0x00); io_outb(0x3fb, 0x80);",
        "  io_outb(0x3f8, 0x03); io_outb(0x3f9, 0x00);",
        "  io_outb(0x3fb, 0x03); io_outb(0x3fa, 0xc7); io_outb(0x3fc, 0x0b);",
        "}",
        "static inline void outb(unsigned char v) {",
        "  io_outb(0xe9, v); /* QEMU debugcon */",
        "  io_outb(0x3f8, v); /* COM1 for browser emulation */",
        "}",
        "void kernel_main(void) {",
        "  serial_init();",
    ]
    for op, value in instructions:
        if op == "print":
            encoded = list((value + "\n").encode("utf-8"))
            data = ", ".join(f"0x{b:02x}" for b in encoded)
            lines.extend([
                "  {",
                f"    const unsigned char message[] = {{{data}}};",
                "    for (unsigned long i = 0; i < sizeof(message); ++i) outb(message[i]);",
                "  }",
            ])
        elif op == "halt":
            break
    lines.extend([
        "#ifdef HTMLK_QEMU_TEST_EXIT",
        '  /* Success exit is only compiled into a dedicated QEMU test artifact. */',
        '  __asm__ volatile ("outb %0, %1" : : "a"((unsigned char)0x10),',
        '                    "Nd"((unsigned short)0xf4));',
        "#endif",
        '  __asm__ volatile ("cli");',
        '  for (;;) __asm__ volatile ("hlt");',
        "}",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description="Compile experimental kernel HTML to freestanding C")
    ap.add_argument("input", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    try:
        generated = compile_html(args.input.read_text(encoding="utf-8"))
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(generated, encoding="utf-8")
    except (CompileError, OSError) as exc:
        ap.error(str(exc))
    print(f"Generated {args.out} (C source only; not a bootable kernel)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
